<?php

declare(strict_types=1);



// Load the application autoloader and database exception classes.
require_once __DIR__ . '/../Bootstrap/autoload.php';

use App\Database\DatabaseUnavailableException;

/**
 * Return the shared PostgreSQL PDO connection.
 *
 * Only this function should create a PDO database connection.
 * Repositories and pages should call database() instead of new PDO().
 */
function database(): PDO
{
    /**
     * Reuse the same connection during one PHP request.
     *
     * If database() gets called multiple times, PHP returns the already
     * established connection rather than opening another PostgreSQL connection.
     */
    static $connection = null;

    if ($connection instanceof PDO) {
        return $connection;
    }

    /**
     * Local database configuration.
     *
     * This file must be excluded from Git because it contains credentials.
     */
    $configFile = __DIR__ . '/database.local.php';

    if (!is_file($configFile)) {
        error_log(
            'Database unavailable: app/config/database.local.php is missing.'
        );

        throw new DatabaseUnavailableException(
            DatabaseUnavailableException::REASON_MISSING_CONFIG
        );
    }

    $config = require $configFile;

    if (!is_array($config)) {
        error_log(
            'Database unavailable: app/config/database.local.php must return an array.'
        );

        throw new DatabaseUnavailableException(
            DatabaseUnavailableException::REASON_INVALID_CONFIG
        );
    }

    /**
     * Test / verification database override.
     *
     * Some CLI verification tools create a temporary PostgreSQL database.
     * This environment variable allows those tools to temporarily override
     * the configured database name.
     *
     * It is deliberately restricted to CLI environments and to database names
     * generated by the HOM'AS verification helper.
     */
    $verificationDatabase = getenv('HOMAS_VERIFICATION_DATABASE');

    if ($verificationDatabase !== false) {
        if (
            !in_array(PHP_SAPI, ['cli', 'cli-server'], true)
            || preg_match(
                '/^homas_candles_verify_check_[a-f0-9]{8}$/',
                $verificationDatabase
            ) !== 1
        ) {
            throw new RuntimeException(
                'Invalid verification database override.'
            );
        }

        $config['database'] = $verificationDatabase;
    }

    /**
     * Read PostgreSQL connection settings.
     *
     * Legacy configuration names are still accepted so old local
     * configuration files do not immediately break.
     */
    $host = $config['host'] ?? null;

    $port = $config['port'] ?? 5432;

    $databaseName =
        $config['database']
        ?? $config['db_name']
        ?? null;

    $username =
        $config['username']
        ?? $config['user_name']
        ?? null;

    $password =
        $config['password']
        ?? $config['psswd']
        ?? null;

    /**
     * Validate the configuration before creating the PDO connection.
     *
     * We intentionally do not include actual credential values in log messages.
     */
    if (
        !is_string($host)
        || $host === ''
        || (!is_int($port) && !ctype_digit((string) $port))
        || !is_string($databaseName)
        || $databaseName === ''
        || !is_string($username)
        || $username === ''
        || !is_string($password)
    ) {
        error_log(
            'Database unavailable: PostgreSQL configuration is incomplete.'
        );

        throw new DatabaseUnavailableException(
            DatabaseUnavailableException::REASON_INCOMPLETE_CONFIG
        );
    }

    /**
     * PostgreSQL PDO DSN.
     *
     * connect_timeout prevents a broken/unreachable database server from
     * making the web request wait for a long system-level timeout.
     */
    $dsn = sprintf(
        'pgsql:host=%s;port=%d;dbname=%s;connect_timeout=5',
        $host,
        (int) $port,
        $databaseName
    );

    try {
        /**
         * PDO configuration:
         *
         * ERRMODE_EXCEPTION
         * Database errors become exceptions instead of silent failures.
         *
         * FETCH_ASSOC
         * Query results use associative arrays by default.
         *
         * EMULATE_PREPARES = false
         * Prefer PostgreSQL's native prepared statements.
         */
        $connection = new PDO(
            $dsn,
            $username,
            $password,
            [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_EMULATE_PREPARES => false,
            ]
        );

        /**
         * Explicitly use UTF-8 for the PostgreSQL client connection.
         *
         * PostgreSQL databases created by the official Docker image normally
         * already use UTF-8, but this ensures the PHP client uses it as well.
         */
        $connection->exec("SET client_encoding TO 'UTF8'");
        // Legacy timestamp-without-time-zone columns consistently store UTC.
        // Business calendar boundaries are converted explicitly by BusinessClock.
        $connection->exec("SET TIME ZONE 'UTC'");
    } catch (PDOException $exception) {
        /**
         * Do not expose PostgreSQL connection details to the browser.
         *
         * Only safe diagnostic information is sent to the application log.
         */
        $diagnostics =
            DatabaseUnavailableException::pdoDiagnostics($exception);

        error_log(sprintf(
            'Database unavailable: PostgreSQL connection failed '
                . '(SQLSTATE %s, driver code %s).',
            $diagnostics['sqlstate'] ?? 'unknown',
            $diagnostics['driver_code'] ?? 'unknown'
        ));

        throw new DatabaseUnavailableException(
            DatabaseUnavailableException::REASON_CONNECTION_FAILED,
            $exception
        );
    }

    return $connection;
}
